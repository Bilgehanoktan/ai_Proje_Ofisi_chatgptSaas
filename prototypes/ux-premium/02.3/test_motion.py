"""Selected prototype tests, no actual agent execution or product test."""
from pathlib import Path
import os,json,math
from playwright.sync_api import sync_playwright
root=Path(__file__).resolve().parent
checks=[]
def check(name,ok):
    assert ok,name
    checks.append(name)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.getenv('CHROMIUM_PATH','/usr/bin/chromium'),args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1080},device_scale_factor=1)
    errors=[];network=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:network.append(r.url) if r.url.startswith(('http:','https:')) else None)
    page.set_content((root/'office.html').read_text(encoding='utf-8'))
    page.wait_for_timeout(200)
    check('four scene avatars',page.locator('[data-avatar]').count()==4)
    check('four cast cards',page.locator('[data-cast]').count()==4)
    check('all decorative idle',page.evaluate("Object.values(motionActors).every(s=>s.state==='idle')"))
    check('all target paths exist',page.evaluate("cast.every(a=>Object.keys(motionModes).every(m=>motionPath(approaches[a.id],motionTarget(a.id,m))))"))
    check('graph edges valid',page.evaluate('motionEdges.every(([a,b])=>motionGraph[a]&&motionGraph[b])'))
    check('unknown role rejected',page.evaluate("motionCommand('unknown','work')===false"))
    check('unknown mode rejected',page.evaluate("motionCommand('orch','unknown')===false"))
    page.locator('[data-cast=engineer]').click()
    check('role selection',page.locator('[data-cast=engineer]').get_attribute('aria-pressed')=='true')
    check('selection keyboard focus',page.evaluate('document.activeElement.dataset.cast')=='engineer')
    page.locator('[data-motion=work]').click()
    check('walking begins',page.locator('[data-avatar=engineer]').get_attribute('data-state')=='walking')
    before=page.locator('[data-avatar=engineer]').get_attribute('transform'); page.wait_for_timeout(160)
    check('real frame movement',before!=page.locator('[data-avatar=engineer]').get_attribute('transform'))
    check('busy rejects retarget',page.evaluate("motionCommand('engineer','rest')===false"))
    page.locator('#motionPause').click();page.wait_for_timeout(80)
    before=page.locator('[data-avatar=engineer]').get_attribute('transform');page.wait_for_timeout(200)
    check('pause freezes position',before==page.locator('[data-avatar=engineer]').get_attribute('transform'))
    check('paused state shown',page.locator('#motionPause').inner_text()=='Devam et')
    def step(seconds):
        page.evaluate('(seconds)=>{for(let t=0;t<seconds;t+=.025)for(const s of Object.values(motionActors))motionAdvance(s,.025);motionPaint();motionStatus()}',seconds)
    step(3)
    check('work settles',page.locator('[data-avatar=engineer]').get_attribute('data-state')=='working')
    check('seat anchor exact',page.evaluate("motionActors.engineer.x===cast[2].seat[0]&&motionActors.engineer.y===cast[2].seat[1]"))
    check('seat foreground occlusion',page.locator('[data-seat-occlusion=engineer]').count()==1)
    before=page.locator('[data-avatar=engineer]').inner_html();step(.12)
    check('typing limb changes',before!=page.locator('[data-avatar=engineer]').inner_html())
    check('other actors stay idle',page.evaluate("cast.filter(a=>a.id!=='engineer').every(a=>motionActors[a.id].state==='idle')"))
    page.locator('#motionFollow').click();check('follow zoom',page.locator('#reset').inner_text()=='155%')
    page.locator('[data-motion=meeting]').click()
    check('stand transition',page.locator('[data-avatar=engineer]').get_attribute('data-state')=='standingUp')
    step(.4);check('meeting walk starts',page.locator('[data-avatar=engineer]').get_attribute('data-state')=='walking')
    path=page.evaluate('motionActors.engineer.path.slice()');check('route through corridor','hub' in path and 'north' in path)
    step(12);check('meeting reached',page.locator('[data-avatar=engineer]').get_attribute('data-state')=='meeting')
    check('meeting seat exact',page.evaluate("motionActors.engineer.node==='engineerMeet'"))
    check('follow camera centered',page.evaluate('Math.abs(cx-P(motionActors.engineer.x,motionActors.engineer.y)[0])<1'))
    page.locator('#reset').click();check('manual camera disables follow',page.evaluate('!motionFollow'))
    page.locator('[data-motion=rest]').click();step(12);check('rest reached',page.locator('[data-avatar=engineer]').get_attribute('data-state')=='resting')
    check('rest seated',page.locator('[data-avatar=engineer]').get_attribute('data-pose')=='seated')
    page.locator('[data-motion=idle]').click();step(12);check('idle return',page.locator('[data-avatar=engineer]').get_attribute('data-state')=='idle')
    page.locator('[data-motion=meeting]').click();step(.8);page.locator('#motionPause').click()
    page.locator('[data-floor="2"]').click();check('passive floor empty',page.locator('[data-avatar]').count()==0)
    before=page.evaluate('JSON.stringify(motionActors.engineer)');page.wait_for_timeout(220);check('passive floor freezes movement',before==page.evaluate('JSON.stringify(motionActors.engineer)'))
    check('passive controls disabled',page.locator('[data-motion=work]').is_disabled())
    check('passive command rejected',page.evaluate("motionCommand('qa','work')===false"))
    page.locator('[data-floor="1"]').click();check('return floor restores four',page.locator('[data-avatar]').count()==4)
    page.locator('#motionReset').click();check('reset all idle',page.evaluate("Object.values(motionActors).every(s=>s.state==='idle'&&!s.path.length)"))
    page.locator('[data-avatar=qa]').focus();page.keyboard.press('Enter');check('keyboard avatar selection',page.locator('[data-cast=qa]').get_attribute('aria-pressed')=='true')
    page.emulate_media(reduced_motion='reduce');page.wait_for_timeout(60);page.locator('[data-motion=work]').click()
    check('reduced motion snap',page.locator('[data-avatar=qa]').get_attribute('data-state')=='working')
    check('reduced motion no path',page.evaluate('motionActors.qa.path.length===0'))
    page.locator('#motionReset').click();page.emulate_media(reduced_motion='no-preference');page.wait_for_timeout(80)
    # Capture reproducible animated frames while paused, no screenshot presented as live runtime.
    page.locator('#motionPause').click();page.locator('[data-cast=orch]').click();page.locator('[data-motion=meeting]').click();step(1.3)
    page.screenshot(path=str(root/'Office.png'),full_page=True)
    step(12);page.locator('button[data-room=meeting]').click();page.screenshot(path=str(root/'Meeting.png'),full_page=True)
    page.locator('#reset').click();page.locator('[data-cast=engineer]').click();page.locator('[data-motion=work]').click();step(4);page.locator('button[data-room=open]').click();page.screenshot(path=str(root/'Working.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844});page.screenshot(path=str(root/'Mobile.png'),full_page=True)
    check('mobile no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    check('no JS errors',not errors);check('no external network',not network)
    version=browser.version;browser.close()
(root/'TEST_EVIDENCE.json').write_text(json.dumps({'scope':'standalone Chromium set_content; real RAF movement and deterministic stepping; no product test','chromium':version,'pass':len(checks),'checks':checks,'product_build':'NOT_RUN','phaser':'NOT_RUN'},indent=2)+'\n')
print(f'{len(checks)}/{len(checks)} PASS')
