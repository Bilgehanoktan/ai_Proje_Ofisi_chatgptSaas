"""Actual Next product smoke + screenshot baseline, run only after pinned build.
Requires isolated loopback product on port 3000. No independent acceptance.
"""
import argparse, json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
parser=argparse.ArgumentParser()
parser.add_argument('--chromium')
parser.add_argument('--output', required=True)
parser.add_argument('--frontend-port',type=int,default=3000)
args=parser.parse_args()
root=Path(__file__).resolve().parents[2]
nav_items=json.loads((root/'product/ai-company-os-frontend/features/uiCatalog.json').read_text(encoding='utf-8'))['nav']
output=Path(args.output); output.mkdir(parents=True, exist_ok=True)
if not 1024 <= args.frontend_port <= 49151: raise ValueError('invalid frontend port')
origin=f'http://127.0.0.1:{args.frontend_port}'
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=args.chromium)
    for width,height in [(1440,900),(390,844)]:
        page=browser.new_page(viewport={'width':width,'height':height}, reduced_motion='reduce')
        errors=[]; external=[]
        page.on('pageerror',lambda error:errors.append(str(error)))
        def route_local(route):
            url=route.request.url
            if url.startswith(origin+'/') or url.startswith('data:') or url.startswith('blob:'+origin+'/'): route.continue_()
            else: external.append(url);route.abort()
        page.route('**/*',route_local)
        for theme in ['dark','light']:
            for index,(name,_) in enumerate(nav_items):
                page.goto(origin+'/',wait_until='networkidle')
                menu=page.get_by_role('button',name='Menü',exact=True)
                if width<=680:
                    expect(menu).to_have_attribute('aria-expanded','false')
                    assert page.locator('h1').bounding_box()['y']<=240, ('mobile heading',theme)
                    expect(page.get_by_role('navigation',name='Ana navigasyon')).to_have_count(0)
                    if index==0:
                        page.keyboard.press('Control+k')
                        search=page.get_by_role('searchbox',name='Menü ara')
                        expect(search).to_be_focused()
                        search.fill('finans')
                        expect(page.get_by_role('navigation',name='Ana navigasyon').get_by_role('button',name='SaaS ve Finans',exact=True)).to_be_visible()
                        search.press('Escape')
                        expect(search).to_have_value('')
                        search.press('Escape')
                        expect(menu).to_be_focused()
                        expect(menu).to_have_attribute('aria-expanded','false')
                    menu.click()
                nav=page.get_by_role('navigation',name='Ana navigasyon')
                expect(nav.locator('button,a')).to_have_count(13)
                if name=='Sanal Ofis':
                    nav.get_by_role('link',name=name,exact=True).click(); expect(page).to_have_url(origin+'/office')
                elif name!='Genel Bakış': nav.get_by_role('button',name=name,exact=True).click()
                if width<=680 and name!='Sanal Ofis':
                    if name=='Genel Bakış': menu.press('Escape')
                    expect(menu).to_have_attribute('aria-expanded','false')
                    if name!='Genel Bakış': expect(page.locator('#main-content')).to_be_focused()
                expect(page.locator('h1')).to_have_text('CEO Command Center' if name=='Genel Bakış' else name)
                if theme=='light':page.get_by_role('button',name='Açık tema').click()
                expect(page.locator('.eds-frame')).to_have_attribute('data-eds-theme',theme)
                # The 52 primary images remain the default view of each destination.
                page.screenshot(path=str(output/f'{width}-{theme}-{index:02}.png'),full_page=True,animations='disabled')
                if name=='Genel Bakış':
                    sections=page.get_by_role('group',name='CEO bölümleri seçimi')
                    summary=sections.get_by_role('button',name='Yönetim özeti',exact=False)
                    operations=sections.get_by_role('button',name='Operasyonlar',exact=False)
                    evidence=sections.get_by_role('button',name='Teknik kanıtlar',exact=False)
                    expect(summary).to_have_attribute('aria-pressed','true')
                    expect(page.get_by_role('region',name='Yönetim bağlamı')).to_be_visible()
                    expect(page.get_by_role('region',name='Bağımsız veri okuma kontrolleri')).to_have_count(0)
                    assert page.evaluate('document.documentElement.scrollHeight<=innerHeight*3'), ('CEO summary height',width,theme)
                    operations.click()
                    expect(operations).to_have_attribute('aria-pressed','true')
                if name in ('Genel Bakış','Sanal Ofis'):
                    office=page.get_by_role('region',name='Sanal ofis',exact=True)
                    expect(office.get_by_role('region',name='Görsel ofis kamerası')).to_be_visible()
                    expect(office.get_by_role('region',name='İstasyon görev gözlemleri')).to_be_visible()
                    expect(office).to_contain_text('JOIN_HOLD')
                    if name=='Genel Bakış':
                        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'), ('CEO operations',width,theme)
                        page.screenshot(path=str(output/f'{width}-{theme}-{index:02}-operations.png'),full_page=True,animations='disabled')
                        evidence.click()
                        expect(page.get_by_role('region',name='Sentetik admission ve bütçe')).to_be_visible()
                        reads=page.get_by_role('region',name='Bağımsız veri okuma kontrolleri')
                        expect(reads).to_contain_text('7/7 bağlantı')
                        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'), ('CEO evidence',width,theme)
                        page.screenshot(path=str(output/f'{width}-{theme}-{index:02}-evidence.png'),full_page=True,animations='disabled')
                        summary.click()
                        expect(page.get_by_role('region',name='CEO / LIFECYCLE')).to_have_count(0)
                if name=='İş ve Denetim':
                    sections=page.get_by_role('group',name='İş ve Denetim bölümleri seçimi')
                    projects=sections.get_by_role('button',name='Project Studio',exact=False)
                    workflow=sections.get_by_role('button',name='Workflow Studio',exact=False)
                    audit=sections.get_by_role('button',name='İş denetimi',exact=False)
                    expect(projects).to_have_attribute('aria-pressed','true')
                    expect(page.get_by_role('region',name='Proje yönetim merkezi')).to_be_visible()
                    expect(page.get_by_role('region',name='Yerel workflow taslak editörü')).to_have_count(0)
                    workflow.click()
                    editor=page.get_by_role('region',name='Yerel workflow taslak editörü')
                    expect(editor).to_be_visible()
                    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'), ('Workflow Studio',width,theme)
                    page.screenshot(path=str(output/f'{width}-{theme}-{index:02}-workflow.png'),full_page=True,animations='disabled')
                    editor.get_by_label('Ön koşul',exact=True).select_option('draft')
                    editor.get_by_label('Bağımlı görev',exact=True).select_option('research')
                    editor.get_by_role('button',name='Taslak bağlantı ekle').click()
                    expect(editor).to_contain_text('Ek taslak bağlantılar · 1')
                    editor.get_by_role('button',name='Geri al',exact=True).click()
                    expect(editor).to_contain_text('Ek taslak bağlantılar · 0')
                    editor.get_by_role('button',name='İleri al',exact=True).click()
                    expect(editor).to_contain_text('Ek taslak bağlantılar · 1')
                    editor.get_by_label('Ön koşul',exact=True).select_option('research')
                    editor.get_by_label('Bağımlı görev',exact=True).select_option('draft')
                    editor.get_by_role('button',name='Taslak bağlantı ekle').click()
                    expect(editor).to_contain_text('Taslak değişmedi')
                    expect(editor).to_contain_text('Ek taslak bağlantılar · 1')
                    audit.click()
                    expect(editor).to_have_count(0)
                    expect(page.get_by_role('region',name='Geliştirme inceleme merkezi')).to_be_visible()
                    expect(page.get_by_role('region',name='Bağımsız veri okuma kontrolleri')).to_contain_text('3/3 bağlantı')
                    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'), ('Work audit',width,theme)
                    page.screenshot(path=str(output/f'{width}-{theme}-{index:02}-audit.png'),full_page=True,animations='disabled')
                    workflow.click()
                    expect(editor).to_contain_text('Ek taslak bağlantılar · 0')
                    projects.click()
                    expect(page.get_by_role('region',name='Proje yönetim merkezi')).to_be_visible()
                if name=='SaaS ve Finans':expect(page.get_by_role('region',name='Finans ve SaaS merkezi')).to_be_visible()
                if name in ('Güvenlik','Raporlar'):expect(page.get_by_role('region',name='Güvenlik ve kanıt merkezi')).to_be_visible()
                assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),(name,width,theme)
        assert not errors,errors;assert not external,external;page.close()
    browser.close()
print('PASS 52 default + 16 section captures; CEO/Work section navigation and draft checks; pixel comparison remains separate')
