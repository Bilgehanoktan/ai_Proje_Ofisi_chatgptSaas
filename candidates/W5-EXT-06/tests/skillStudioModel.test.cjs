const test=require('node:test'),assert=require('node:assert/strict');
const path=require('node:path');
const {readSkillCatalog,filterSkills,selectedSkill,emptyFilter,skillBoundary}=require(process.env.EXT06_MODEL);
const src=require(path.join(path.dirname(process.env.EXT06_MODEL),'skillData.json'));
const clone=()=>JSON.parse(JSON.stringify(src));
const view=()=>{const r=readSkillCatalog();assert.equal(r.ok,true);return r.catalog};
const filter=(f={})=>filterSkills(view(),{...emptyFilter(),...f}).map(s=>s.skill_id);
const hold=(mut)=>{let c=clone();mut(c);const r=readSkillCatalog(c);assert.equal(r.ok,false);assert.equal('catalog' in r,false)};
test('historical catalog',()=>{const c=view();assert.equal(c.skills.length,3);assert.equal(c.active_count,0);assert.equal(c.installed_count,0);assert.equal(c.actual_assignments,null);assert.equal(c.actual_installed_count,null);assert.equal(c.actual_active_count,null)});
test('all skills',()=>assert.deepEqual(filter(),['superpowers','ui-ux-pro-max','watch']));
test('research',()=>assert.deepEqual(filter({role:'research'}),['ui-ux-pro-max','watch']));
test('engineer',()=>assert.deepEqual(filter({role:'engineer'}),['superpowers','ui-ux-pro-max']));
test('qa',()=>assert.deepEqual(filter({role:'qa'}),['superpowers']));
test('orchestrator no match',()=>assert.deepEqual(filter({role:'orchestrator'}),[]));
test('research department',()=>assert.deepEqual(filter({department:'Araştırma'}),['ui-ux-pro-max','watch']));
test('engineering department',()=>assert.deepEqual(filter({department:'Mühendislik'}),['superpowers','ui-ux-pro-max']));
test('quality department',()=>assert.deepEqual(filter({department:'Kalite'}),['superpowers']));
test('management department empty',()=>assert.deepEqual(filter({department:'Yönetim'}),[]));
test('combined same role and department',()=>assert.deepEqual(filter({role:'research',department:'Araştırma'}),['ui-ux-pro-max','watch']));
test('cross-role department must not join',()=>assert.deepEqual(filter({role:'engineer',department:'Araştırma'}),[]));
test('trimmed search',()=>assert.deepEqual(filter({query:'  watch  '}),['watch']));
test('search by path',()=>assert.deepEqual(filter({query:'contrast_review.mjs'}),['ui-ux-pro-max']));
test('search by version',()=>assert.equal(filter({query:'0.1.0-ext05'}).length,3));
test('invalid role',()=>assert.deepEqual(filter({role:'administrator'}),[]));
test('invalid department',()=>assert.deepEqual(filter({department:'all-departments'}),[]));
test('query bounds',()=>assert.deepEqual(filter({query:'a'.repeat(201)}),[]));
test('query type',()=>assert.deepEqual(filter({query:null}),[]));
test('selected visible only',()=>assert.equal(selectedSkill(filterSkills(view(),{...emptyFilter(),role:'qa'}),'watch'),null));
test('selection found',()=>assert.equal(selectedSkill(view().skills,'watch').skill_id,'watch'));
