const test=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),crypto=require('node:crypto');
const model=require(process.env.EXT06_MODEL);
const raw=fs.readFileSync(process.env.EXT07_PROJECTION);
const projection=JSON.parse(raw);
const result=model.readSkillCatalog();
assert.equal(result.ok,true);
const ui=result.catalog;
const expected='436ceb58f36690087324d6ebdfbdbd6601c60427';
const blob=crypto.createHash('sha1').update('blob '+raw.length+'\0').update(raw).digest('hex');
const select=(id)=>ui.skills.find(r=>r.skill_id===id);
const clone=(x)=>JSON.parse(JSON.stringify(x));
test('fresh Python projection is exact historical blob',()=>assert.equal(blob,expected));
test('top-level projection fields match Studio',()=>{for(const [k,v] of Object.entries(projection))if(k!=='skills')assert.deepEqual(ui[k],v)});
test('exactly three candidate identities',()=>assert.deepEqual(ui.skills.map(x=>x.skill_id),projection.skills.map(x=>x.skill_id)));
for(const s of projection.skills)test('all 14 Python row fields match '+s.skill_id,()=>{const row=select(s.skill_id);assert.equal(Object.keys(s).length,14);for(const [k,v] of Object.entries(s))assert.deepEqual(row[k],v,k)});
for(const s of projection.skills)for(const r of s.reviews)test('role review remains non-authoritative '+s.skill_id+'/'+r.role_hint,()=>{const row=select(s.skill_id).reviews.find(x=>x.role_hint===r.role_hint);assert.deepEqual(row,r);assert.equal(row.decision,'HOLD');for(const k of ['enabled','grant_created','dispatch_allowed','independent_verified'])assert.equal(row[k],false);assert.deepEqual(row.effective_tools,[])});
test('Python projection is not accepted as full UI catalog',()=>assert.equal(model.readSkillCatalog(projection).ok,false));
test('tampered Python role output cannot become a UI grant',()=>{const c=clone(ui);c.skills[0].reviews[0].grant_created=true;assert.equal(model.readSkillCatalog(c).ok,false)});
test('all actual inventory fields remain unknown',()=>{for(const k of ['actual_installed_count','actual_active_count','actual_assignments'])assert.equal(ui[k],null)});
